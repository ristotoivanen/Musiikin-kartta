import {test,expect} from '@playwright/test';

test.beforeEach(async({page})=>{
  await page.addInitScript(()=>{Math.random=()=>0;});
  await page.goto('/sointipaja-prototyyppi.html');
  await page.clock.install();
});

test('challenge: select cohorts, neutral root, real freeze, deadline, record and return',async({page})=>{
  const requests:string[]=[];
  await page.route('**/assets/audio/soinnut/*',async route=>{requests.push(route.request().url());await route.abort();});
  await page.locator('#mode-challenge').click();
  await expect(page.locator('#challenge-pool')).toHaveText('11 eri sointua pelissä.');
  await expect(page.locator('#challenge-penalty')).toHaveCount(0);
  await expect(page.locator('#challenge-setup')).toContainText('neljäksi sekunniksi');
  const checks=page.locator('#challenge-levels input');
  await checks.nth(0).uncheck();
  await expect(page.locator('#challenge-pool')).toHaveText('4 eri sointua pelissä.');
  await checks.nth(1).uncheck();
  await expect(page.locator('#challenge-start')).toBeDisabled();
  await checks.nth(0).check();
  await page.locator('#challenge-duration').selectOption('30');
  await page.locator('#challenge-start').click();
  const roots=page.locator('#roots'),answers=page.locator('#answers');
  await expect(roots.locator('button')).toHaveText(['C','D','E','F','G','A','B']);
  await expect(page.locator('#challenge-score')).toHaveText('0');
  await expect(page.locator('#practice-audio')).toBeHidden();
  await expect(page.locator('#board button')).toHaveCount(0);
  await roots.getByRole('button',{name:'G',exact:true}).click();
  await expect(page.locator('#challenge-errors')).toHaveText('0');
  await answers.getByRole('button',{name:'G',exact:true}).click();
  await expect(page.locator('#challenge-errors')).toHaveText('1');
  await expect(page.locator('#challenge-lock')).toContainText('Lukitus');
  await expect(roots.getByRole('button',{name:'C',exact:true})).toHaveAttribute('aria-disabled','true');
  await page.clock.runFor(1000);
  await roots.getByRole('button',{name:'C',exact:true}).dispatchEvent('click');
  await expect(roots.getByRole('button',{name:'G',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('#challenge-score')).toHaveText('0');
  await page.clock.runFor(3100);
  await expect(page.locator('#challenge-lock')).toBeEmpty();
  await roots.getByRole('button',{name:'C',exact:true}).click();
  await answers.getByRole('button',{name:'C',exact:true}).click();
  await expect(page.locator('#challenge-score')).toHaveText('1');
  await expect(answers.locator('button')).toHaveCount(0);
  await roots.getByRole('button',{name:'G',exact:true}).click();
  await answers.getByRole('button',{name:'G',exact:true}).click();
  await expect(page.locator('#challenge-score')).toHaveText('2');
  expect(requests).toHaveLength(0);
  await page.clock.fastForward(30000);
  await expect(page.locator('#challenge-result-heading')).toHaveText('Aika loppui!');
  await expect(page.locator('#challenge-result-score')).toHaveText('2 pistettä');
  await expect(page.locator('#challenge-result-first')).toHaveText('1');
  await expect(page.locator('#challenge-result-errors')).toHaveText('1');
  await expect(page.locator('#challenge-result-penalty')).toHaveText('4 s');
  await expect(page.locator('#challenge-result-best')).toHaveText('2');
  await expect(page.locator('#challenge-result-review')).toContainText('C (1)');
  await page.locator('#challenge-replay').click();
  await expect(page.locator('#challenge-score')).toHaveText('0');
  await page.locator('#challenge-stop').click();
  await expect(page.locator('#challenge-best')).toContainText('2 pistettä');
  await expect(page.locator('#challenge-setup-note')).toContainText('ei tallennettu');
  await page.locator('#challenge-duration').selectOption('60');
  await expect(page.locator('#challenge-best')).toContainText('Ei tallennettua');
  await page.locator('#mode-practice').click();
  await expect(page.locator('#progress')).toHaveText('Sointu 1 / 4');
  await expect(page.locator('#practice-audio')).toBeVisible();
  await expect(page.locator('#board button')).toHaveCount(5);
});

test('challenge: visiting settings does not reset an unfinished practice round',async({page})=>{
  await page.route('**/assets/audio/soinnut/*',route=>route.abort());
  await page.locator('#answers').getByRole('button',{name:'C',exact:true}).click();
  await page.locator('#next').click();
  await expect(page.locator('#progress')).toHaveText('Sointu 2 / 4');
  await page.locator('#mode-challenge').click();
  await page.locator('#mode-practice').click();
  await expect(page.locator('#progress')).toHaveText('Sointu 2 / 4');
});

test('challenge: all 24 chords selectable, mobile layout, expiry during penalty',async({page})=>{
  await page.setViewportSize({width:320,height:844});
  await page.locator('#mode-challenge').click();
  const checks=page.locator('#challenge-levels input');
  await checks.nth(2).check();await checks.nth(3).check();
  await expect(page.locator('#challenge-pool')).toHaveText('24 eri sointua pelissä.');
  await page.locator('#challenge-duration').selectOption('30');
  await page.locator('#challenge-start').click();
  const roots=page.locator('#roots');
  await roots.getByRole('button',{name:'C',exact:true}).click();
  await expect(page.locator('#answers button')).toHaveText(['C','C7','Cmaj7','Cadd9']);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  await page.clock.fastForward(28000);
  await page.locator('#answers').getByRole('button',{name:'C7',exact:true}).click();
  await expect(page.locator('#challenge-lock')).toContainText('Lukitus');
  await page.clock.fastForward(5000);
  await expect(page.locator('#challenge-result-heading')).toBeVisible();
  await expect(page.locator('#challenge-result-score')).toHaveText('0 pistettä');
  await expect(page.locator('#challenge-result-errors')).toHaveText('1');
});
